#!/usr/bin/env node
/*
 * Writes css/generated/ranges.css from the section schemas: one attribute
 * selector per value of every range setting, so a numeric setting reaches
 * CSS as a data attribute and no style is ever printed in a page.
 *
 *   .s-hero[data-overlay="55"]{--overlay:55}
 *
 * Run after changing a range setting in schemas/sections: node bin/ranges.mjs
 *
 * An extension writes the rules of its own sections into its own stylesheet:
 *
 *   node bin/ranges.mjs --schemas <its parts folder>/schemas/sections --out <its stylesheet>
 *
 * Its sections' class is s-{extension}--{name} (the type with its dot as --).
 * The file named by --out is written whole, so keep the rules in a stylesheet
 * of their own and import it from the extension's main one.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const option = (name) => {
  const at = process.argv.indexOf(`--${name}`);
  return at > -1 ? process.argv[at + 1] : null;
};
const extensionDir = option('schemas');
const extensionOut = option('out');
if (Boolean(extensionDir) !== Boolean(extensionOut)) {
  console.error('Give both --schemas and --out, or neither.');
  process.exit(1);
}
const dir = extensionDir ? path.resolve(extensionDir) : path.join(root, 'schemas/sections');
const target = extensionOut ? path.resolve(extensionOut) : path.join(root, 'css/generated/ranges.css');
const out = [
  extensionDir
    ? '/* Generated by Xelga\'s bin/ranges.mjs from the extension\'s section schemas. Do not edit by hand. */'
    : '/* Generated by bin/ranges.mjs from schemas/sections. Do not edit by hand. */',
];

const values = (s) => {
  const list = [];
  const count = Math.round((s.max - s.min) / s.step);
  for (let i = 0; i <= count; i += 1) list.push(Number((s.min + i * s.step).toFixed(4)));
  return list;
};

const dashed = (key) => key.replace(/_/g, '-');

for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const schema = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  const cls = extensionDir ? `s-${String(schema.type).replace('.', '--')}` : schema.class || `s-${schema.type}`;
  const rules = [];
  for (const s of schema.settings || []) {
    if (s.type !== 'range') continue;
    for (const v of values(s)) rules.push(`.${cls}[data-${dashed(s.key)}="${v}"]{--${dashed(s.key)}:${v}}`);
  }
  for (const block of schema.blocks?.types || []) {
    for (const s of block.settings || []) {
      if (s.type !== 'range') continue;
      for (const v of values(s)) rules.push(`.${cls} [data-block-type="${block.type}"][data-${dashed(s.key)}="${v}"]{--${dashed(s.key)}:${v}}`);
    }
  }
  if (rules.length) out.push(`\n/* ${schema.type} */`, ...rules);
}

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, `${out.join('\n')}\n`);
console.log(`${path.relative(process.cwd(), target)}: ${out.length - 1} lines`);
